# 画面の並び(欄の名前, 記号の頭)
GROUPS = [
    ('今', ('S', 'K', 'U', 'H', 'B', 'D', 'Y')),
    ('前走', ('P', 'L')),
    ('今回', ('R', 'C', 'A', 'J', 'G', 'M')),
    ('馬', ('Q', 'T')),
    ('結論', ('E', 'V')),
]
ORDER = list(LABEL)


def head(code):
    return code.rstrip('0123456789')


def line(codes):
    codes = [c for c in codes if c in LABEL]
    if 'D2' in codes and 'D1' in codes:
        codes = [c for c in codes if c != 'D1']
    out = []
    for name, heads in GROUPS:
        cs = sorted((c for c in codes if head(c) in heads), key=ORDER.index)
        if cs:
            out.append(f'{name}: ' + '・'.join(LABEL[c] for c in cs))
    return ' / '.join(out)
