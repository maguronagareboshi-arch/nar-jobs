def tags(text):
    """談話の本文 → [(欄, 型), ...](欄の順・重なりなし)。"""
    t = text if isinstance(text, str) else ''
    got = []
    for slot, lab, rx, neg in _C:
        hit = False
        for m in rx.finditer(t):
            if neg and NEG.match(t[m.end():m.end() + 8]):
                continue
            hit = True
            break
        if hit:
            got.append((slot, lab))
    s = set(got)
    if any(a == '病気' and b != '治療(笹針など)' for a, b in s):  # 病気の結び(0.52 倍 / 1.08 倍・out/danwa_deep4.md)
        if ILL_BAD.search(t):
            s.add(('病気', '→ その後 調整不足'))
        elif ILL_OK.search(t) and not ILL_UNR.search(t):
            s.add(('病気', '→ 回復と明言'))
    for loser, winner in _DROP.items():
        if loser in s and winner in s:
            s.discard(loser)
    order = [r[1] for r in RULES] + ['→ その後 調整不足', '→ 回復と明言']
    return sorted(s, key=lambda x: (SLOTS.index(x[0]), order.index(x[1])))


def summary(text):
    """→ '状態: 好調・上向き / 事情: 休み明け・放牧明け / 結論: 強気(勝ち負け)'(型が無ければ '')。"""
    by = {}
    for slot, lab in tags(text):
        by.setdefault(slot, []).append(lab)
    return ' / '.join(f'{s}: ' + '、'.join(by[s]) for s in SLOTS if s in by)
