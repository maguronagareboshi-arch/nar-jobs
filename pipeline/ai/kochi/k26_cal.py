"""他場版 v3n の 3 着内の率の直し(2026-10-11・確かめ = v3 の out/v3n_cal.md・決め書 out/v3n_cal_plan.md)。

p3 = 1 ÷ (1 + exp(−(a + b·z + c·z²)))・z = log(混ぜた割合 s)。a・b・c は頭数の帯ごと(選ぶ期間 2024-09〜2025-08 で最尤)。
今までの p3 = 3 × s は人気薄で高すぎ(見込み 2% 以下で実際は 3〜4 割)= 確かめ 全馬 3 着内 +9.3 ± 8.6 ×10^-4・印と ◎ は変わらない。
割合がごく小さい所(z < −b/2c)で曲線が折り返すので、そこは平らに止める(確かめで +9.2 → +9.3)。
"""
import numpy as np

CAL = [(8, [5.244582, 3.416517, 0.326532]), (10, [4.734881, 2.986576, 0.249808]), (12, [4.292215, 2.662682, 0.200006]), (99, [3.941271, 2.385813, 0.158204])]  # (この頭数まで, [a, b, c])


def p3(s, n):
    """s = 1 レースの混ぜた割合(合計 1)・n = 頭数 → 3 着内の率"""
    a, b, c = next(v for k, v in CAL if n <= k)
    z = np.log(np.clip(np.asarray(s, float), 1e-6, 1))
    if c > 0:
        z = np.maximum(z, -b / (2 * c))
    return np.clip(1 / (1 + np.exp(-(a + b * z + c * z * z))), 0.001, 0.999)
