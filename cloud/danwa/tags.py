def clean_hk(got):
    """Haiku の札 → 一覧の順・一覧に無い札は捨てる。"""
    got = {str(x).strip() for x in (got or [])}
    return [t for t in HK_LIST if t in got]


def disease_tags(comment):
    """語句ルールの病気の札(型名そのまま・M に無いもの)。"""
    return [t for t in note_tags(comment) if t not in HK_DEF]


def merge_tags(hk, comment):
    """保存する札= Haiku の札(一覧の順)+ 語句ルールの病気(後ろ)。hk=None(取れなかった)は語句ルールの札を M の順で。"""
    if hk is None:
        base = [t for t in HK_LIST if t in set(note_tags(comment))]
    else:
        base = clean_hk(hk)
    return base + [t for t in disease_tags(comment) if t not in base]


def pg_array(tags):
    """['a','b'] → '{a,b}'(札名に , { } " は無い前提・あれば引用)。"""
    def q(s):
        return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"' if re.search(r'[,{}"\s\\]', s) else s
    return '{' + ','.join(q(s) for s in tags) + '}'


