// §128b2 見出しの直下に出すのは **導入の1〜2文だけ**(`explain`)。
//   ①②③の本体は表やカードの**下**に畳んで置く(`explainFull`)= ⛔文章は閉じていても HTML に全部入っている。
//   key が表に無ければ空文字(=何も出さない)。opts.name / opts.prefix … 場ごとのページ(/jockey-change/<場>)の差し替え。
function entry(key) {
  return Object.prototype.hasOwnProperty.call(EXPLAIN, key) ? EXPLAIN[key] : null;
}

function filler(opts) {
  const o = opts || {};
  return (s) => (o.name ? String(s).split('{場}').join(o.name) : String(s));
}

// 見出しの直下= 導入の1〜2文だけ
export function explain(key, ctx, opts) {
  const e = entry(key);
  if (!e || !ctx || !e.lead) return '';
  return '<p class="ex-lead">' + ctx.ui.escapeHTML(filler(opts)(e.lead)) + '</p>';
}

// 表やカードの下= ①このページで分かること ②数え方と作り方 ③注意 の3節(既定は閉じる)
export function explainFull(key, ctx, opts) {
  const e = entry(key);
  if (!e || !ctx) return '';
  const { ui, router } = ctx;
  const fill = filler(opts);
  const p = (s) => '<p class="lede">' + ui.escapeHTML(fill(s)) + '</p>';
  const h = (i) => '<h2 class="ex-h">' + ui.escapeHTML(HEADS[i]) + '</h2>';
  const links = typeof e.links === 'function' ? e.links(opts || {}) : e.links;
  const nav = (links || []).map(([text, path]) => router.link(path, ui.escapeHTML(text), { class: 'more' })).join(' ');
  // ⛔中で二重に畳まない(§128b の ex-fold は廃止)。閉じていてもクローラーと審査員は全文を読める
  return '<details class="explain ex-full"><summary>このページの読み方</summary>' + ui.card(
    h(0) + e.what.map(p).join('') +
    h(1) + e.how.map(p).join('') +
    h(2) + e.care.map(p).join('') +
    (nav ? '<p class="note ex-links">' + nav + '</p>' : '')) + '</details>';
}

// tests 用= 本文だけを取り出す(⛔画面からは使わない)
export const EXPLAIN_KEYS = Object.keys(EXPLAIN);
export function explainText(key) {
  const e = entry(key);
  if (!e) return '';
  return [e.lead].concat(e.what, e.how, e.care).join('');
}
